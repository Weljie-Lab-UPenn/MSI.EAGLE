suppressPackageStartupMessages(library(Cardinal))
pkgload::load_all('.', quiet=TRUE)
m <- seq(100,900,length.out=20)
a <- data.frame(feature=seq_along(m),obs=m,ppm_raw=2+3*m/1000,use=TRUE,reason='Accepted')
f <- cal_fit(a,robust=FALSE)
stopifnot(f$model=='linear',max(abs(cal_axis(m,f)$mz_calibrated-m/(1+(2+3*m/1000)*1e-6)))<1e-9)
a$ppm_raw <- 0; stopifnot(cal_fit(a,robust=FALSE)$model=='unchanged')
a$ppm_raw <- 3; stopifnot(cal_fit(a[1:3,],robust=FALSE)$model=='constant')
x <- MSImagingExperiment(spectraData=SimpleList(intensity=matrix(seq_len(60),20,3)),featureData=MassDataFrame(mz=m),pixelData=PositionDataFrame(coord=data.frame(x=1:3,y=rep(1,3)),run=rep("run1",3)),centroided=TRUE)
y <- cal_apply(x,f); z <- cal_restore(y)
stopifnot(identical(as.matrix(spectra(x)),as.matrix(spectra(y))),isTRUE(all.equal(mz(x),mz(z))),identical(as.data.frame(pData(x)),as.data.frame(pData(y))))
stopifnot(inherits(try(cal_apply(y,f),silent=TRUE),'try-error'))
p <- paste0(tempfile(),".imzML");writeImzML(y,p); yy <- readMSIData(p)
stopifnot(isTRUE(all.equal(as.numeric(mz(y)),as.numeric(mz(yy)),tolerance=1e-7)))
