pkgload::load_all('.',quiet=TRUE)
r <- data.frame(name=c('A','B','C'),adduct='[M+H]+',formula='CH4',theo=c(100,200,300),n_alt_5ppm=0,alternatives='')
a <- cal_candidates(c(100,100.001,200),c(10,1,20),r)
stopifnot(identical(a$mean_intensity,c(10,20,NA_real_)),a$dominance[1]==10,is.infinite(a$dominance[2]))
d <- cal_anchor_display(a)
stopifnot(d$dominance[1]=='10',d$dominance[2]=='No competing peak',d$dominance[3]=='Unavailable',is.infinite(a$dominance[2]))
widget <- DT::datatable(d)
encoded <- jsonlite::toJSON(widget$x$data)
stopifnot(grepl('No competing peak',encoded,fixed=TRUE),identical(d$mean_intensity,a$mean_intensity))
cat('Finite/no-competitor/missing dominance displays and mean-intensity mapping passed; numeric fit values preserved\n')
